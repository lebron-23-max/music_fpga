`timescale 1ns / 1ps
//=============================================================================
// audio_volume.v —— 最终输出主音量（数字音量）
//=============================================================================
//
// 位置：放在两种音色“二选一”之后、I2S 发送之前，所以它控制的是最终输出，
//       与音色、音高、混音路数都无关。
//
// 算法：sample_out = sample_in × volume / 256
//   volume = 0   -> 静音
//   volume = 128 -> 0.5 倍（-6 dB）
//   volume = 255 -> 0.996 倍（≈ 原音量，接近满幅）
//
// 因为 volume ≤ 255，输出幅度不会超过输入，所以这一级本身不会产生新削波；
// 前面的 audio_mixer 已经做过 16 位饱和，这里只做缩放。
//
// 资源：1 个 16×9 有符号乘法器（映射到 DSP）。
//=============================================================================
module audio_volume (
    input  wire signed [15:0] sample_in,   // 上一级混音输出
    input  wire [7:0]         volume,      // 0~255：0=静音，255≈满幅
    output wire signed [15:0] sample_out   // 缩放后的最终输出
);
    // 16 位有符号 × 9 位无符号 -> 24 位有符号（幅值不会溢出：32768×255 < 2^23）
    wire signed [23:0] product = sample_in * $signed({1'b0, volume});

    // 右移 8 位 = 除以 256
    assign sample_out = product[23:8];

endmodule