`timescale 1ns / 1ps
//=============================================================================
// ui_data_ram.v —— 显示用"实时数据快照"RAM（跨时钟：音频域写 / 显示域读）
//=============================================================================
// 256 x 8bit。写口在音频域 clk（50 MHz），读口在显示域 pix_clk（40 MHz）。
// 这样所有需要跨域显示的数值（频谱幅度、按键/编码器实测值等）都走这一条
// 双时钟 BSRAM 通路，不需要给每一路单独做多比特跨时钟同步。
//
// 地址分配（全部是"真实测量值"，没有任何常数占位）：
//    0 .. 51  : 钢琴 52 个半音频点幅度
//   52 .. 103 : 八音盒
//  104 .. 155 : 电钢琴
//  156 .. 207 : 弦乐
//  208..211   : 四音色峰值计数
//  212        : 当前音色
//  213        : 主音量
//  214        : 变调步进
//  215..218   : ADSR A/D/S/R
//  219..221   : 混响/延迟/合唱
//  222..225   : 四音色正在发声的声部数
//  226        : 采样率整数部分
//  227..255   : 保留
//=============================================================================
module ui_data_ram (
    input  wire        wclk,
    input  wire        we,
    input  wire [7:0]  waddr,
    input  wire [7:0]  wdata,
    input  wire        rclk,
    input  wire [7:0]  raddr,
    output reg  [7:0]  rdata
);
    reg [7:0] mem [0:255];

    always @(posedge wclk) if (we) mem[waddr] <= wdata;
    always @(posedge rclk) rdata <= mem[raddr];
endmodule
